/*
 * Exterior design data for every generation.
 * Proportions are in metres and were estimated from side/front/rear reference views of each car;
 * front/rear shapes use [u, dy] (u = fraction of half-width, dy = metres from the hood edge / top of the tail).
 */

// ---------- shared shape builders ----------

/** BMW kidney (right one; mirrored by the renderer). */
const kidney = (uIn: number, uOut: number, top: number, bot: number, r = 0.03, slant = 0.01): P[] =>
  round(
    [
      [uIn, top],
      [uOut - slant, top - 0.005],
      [uOut, top - 0.04],
      [uOut - slant * 0.5, bot + 0.02],
      [uOut - 0.03, bot],
      [uIn + 0.02, bot],
      [uIn, bot + 0.04],
    ],
    r,
  );

const kid = (shape: P[], texture: GrilleSpec['texture'] = 'vbars', frame: GrilleSpec['frame'] = 'chrome'): GrilleSpec => ({
  shapes: [shape],
  mirror: true,
  texture,
  frame,
  logo: [0, 0.01],
  logoScale: 1,
});

const singleframe = (wTop: number, wMid: number, wBot: number, top: number, mid: number, bot: number, texture: GrilleSpec['texture'], frame: GrilleSpec['frame'] = 'chrome', bars?: number[]): GrilleSpec => ({
  shapes: [octagon(wTop, wMid, wBot, top, mid, bot, 0.025)],
  texture,
  frame,
  logo: [0, top - 0.055],
  logoScale: 1,
  bars,
});

const mbGrille = (wTop: number, wBot: number, top: number, bot: number, texture: GrilleSpec['texture'], bars: number[] = [], logo: P | null = [0, (top + bot) / 2], logoScale = 1.5): GrilleSpec => ({
  shapes: [
    round(
      [
        [-wTop, top],
        [wTop, top],
        [wBot, bot],
        [-wBot, bot],
      ],
      0.035,
    ),
  ],
  texture,
  frame: 'chrome',
  logo,
  logoScale,
  bars,
});

const L = (shape: P[], extra: Partial<LightSpec> = {}): LightSpec => ({ shape: round(shape, 0.02), ...extra });

const sideIntake = (u0: number, u1: number, top: number, bot: number, texture: Design['intakes'][number]['texture'] = 'honeycomb', slope = 0.04) => ({
  shape: round(
    [
      [u0, top - slope],
      [u1, top],
      [u1 + 0.02, bot + 0.02],
      [u0 + 0.04, bot],
    ],
    0.025,
  ),
  texture,
  mirror: true,
});
const centreIntake = (w: number, top: number, bot: number, texture: Design['intakes'][number]['texture'] = 'mesh', wBot = w * 0.92) => ({
  shape: round(
    [
      [-w, top],
      [w, top],
      [wBot, bot],
      [-wBot, bot],
    ],
    0.03,
  ),
  texture,
});

