#!/usr/bin/env node
/**
 * Search Sketchfab's public API for downloadable models of every generation in the catalogue
 * and write MODEL_SOURCES.md. No account needed.   node scripts/find-models.mjs
 */
import { build } from 'esbuild';
import fs from 'node:fs';
import https from 'node:https';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tmp = path.join(root, 'node_modules/.cache/kyc-catalog.mjs');
fs.mkdirSync(path.dirname(tmp), { recursive: true });
await build({ entryPoints: [path.join(root, 'src/data/catalog.ts')], bundle: true, format: 'esm', outfile: tmp, logLevel: 'silent' });
const { BRANDS } = await import(pathToFileURL(tmp).href);

const get = (url) =>
  new Promise((resolve, reject) =>
    https
      .get(url, { headers: { 'User-Agent': 'knowyourcar' } }, (res) => {
        const c = [];
        res.on('data', (d) => c.push(d));
        res.on('end', () => (res.statusCode >= 400 ? reject(new Error(String(res.statusCode))) : resolve(JSON.parse(Buffer.concat(c).toString()))));
      })
      .on('error', reject),
  );
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function search(q) {
  const url = `https://api.sketchfab.com/v3/search?type=models&downloadable=true&sort_by=-likeCount&count=12&q=${encodeURIComponent(q)}`;
  try {
    return (await get(url)).results ?? [];
  } catch {
    await sleep(2000);
    return (await get(url)).results ?? [];
  }
}

const lines = [
  '# Downloadable model candidates',
  '',
  'Best-liked downloadable Sketchfab models per generation (auto-generated by `node scripts/find-models.mjs`).',
  'Check each one matches the exact generation and that its licence suits your use, then:',
  '',
  '```bash',
  'SKETCHFAB_TOKEN=… node scripts/fetch-model.mjs <genId> <model url>',
  '```',
  '',
];
for (const brand of BRANDS) {
  lines.push(`## ${brand.name}`, '');
  for (const model of brand.models)
    for (const g of model.generations) {
      const short = brand.name.replace('-Benz', '');
      const queries = [`${short} ${g.variant} ${g.code}`, `${short} ${model.name.split('/')[0].trim()} ${g.code}`, `${short} ${g.variant}`];
      let res = [];
      for (const q of queries) {
        res = (await search(q)).filter((r) => !/low.?poly/i.test(r.name) && (r.faceCount ?? 0) > 30000);
        await sleep(400);
        if (res.length) break;
      }
      lines.push(`### ${g.variant} (${g.code}) — \`${g.id}\``, '');
      if (!res.length) lines.push('_No downloadable match found — try searching manually._', '');
      for (const r of res.slice(0, 3))
        lines.push(`- [${r.name}](${r.viewerUrl}) — ${r.user?.displayName}, ${r.license?.label ?? '?'}, ${Math.round((r.faceCount ?? 0) / 1000)}k faces, ♥ ${r.likeCount}`);
      lines.push('');
      process.stdout.write('.');
    }
}
fs.writeFileSync(path.join(root, 'MODEL_SOURCES.md'), lines.join('\n'));
console.log('\n✓ wrote MODEL_SOURCES.md');
